// Writes src-tauri/licenses/THIRD-PARTY-NOTICES.txt: the licence text of every Rust crate and
// npm package that ends up inside the installed app. Run it after changing dependencies:
//
//   node scripts/notices.mjs
//
// Only what ships is listed: crates reachable through normal (not build or dev) dependencies
// on Windows x64, and npm packages that are not dev-only. Identical licence texts are printed once.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LICENCE_FILE = /^(licen[sc]e|copying|notice|unlicense)/i;

/** Licence files in a package folder, as { file, text }. */
function licenceFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => LICENCE_FILE.test(name))
    .sort()
    .map((name) => ({ file: name, text: readFileSync(join(dir, name), "utf8").replace(/\r\n/g, "\n").trim() }))
    .filter((f) => f.text);
}

function rustPackages() {
  const metadata = JSON.parse(
    execFileSync(
      "cargo",
      ["metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-pc-windows-msvc"],
      { cwd: join(root, "src-tauri"), maxBuffer: 256 * 1024 * 1024 },
    ),
  );
  const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
  const shipped = new Set();
  const queue = [metadata.resolve.root];
  while (queue.length) {
    const id = queue.pop();
    if (shipped.has(id)) continue;
    shipped.add(id);
    for (const dep of nodes.get(id).deps) {
      // kind null is a normal dependency; "build" and "dev" never reach the installed app.
      if (dep.dep_kinds.some((k) => k.kind === null)) queue.push(dep.pkg);
    }
  }
  return metadata.packages
    .filter((p) => shipped.has(p.id) && p.id !== metadata.resolve.root)
    .map((p) => ({
      name: p.name,
      version: p.version,
      licence: p.license ?? "see licence file",
      source: p.repository ?? `https://crates.io/crates/${p.name}`,
      files: licenceFiles(dirname(p.manifest_path)),
    }));
}

function npmPackages() {
  const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
  return Object.entries(lock.packages)
    .filter(([path, info]) => path && !info.dev)
    .map(([path, info]) => {
      const manifest = JSON.parse(readFileSync(join(root, path, "package.json"), "utf8"));
      const repository = typeof manifest.repository === "string" ? manifest.repository : manifest.repository?.url;
      const name = path.replace(/^.*node_modules\//, "");
      return {
        name,
        version: info.version,
        licence: manifest.license ?? "see licence file",
        source: repository ?? `https://www.npmjs.com/package/${name}`,
        files: licenceFiles(join(root, path)),
      };
    });
}

const byName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version);
const rust = rustPackages().sort(byName);
const npm = npmPackages().sort(byName);

// Licence texts, each printed once and referred to by number.
const texts = new Map();
const refs = (pkg) =>
  pkg.files.map(({ file, text }) => {
    const key = createHash("sha256").update(text).digest("hex");
    if (!texts.has(key)) texts.set(key, { number: texts.size + 1, text });
    return `${file} [${texts.get(key).number}]`;
  });

const lines = [
  "Third-party notices for inkd",
  "============================",
  "",
  "inkd itself is under the MIT licence. It is built from the open-source software listed",
  "below. Each entry names its licence and where its text is printed further down, by number.",
  "This file is generated by scripts/notices.mjs.",
  "",
  "DirectML.dll and the TexTeller model have their own files in this folder; see README.txt.",
  "",
  "ONNX Runtime",
  "  Built into inkd.exe through the ort crate. Copyright (c) Microsoft Corporation.",
  "  MIT licence. https://github.com/microsoft/onnxruntime",
  "",
];
const missing = [];
for (const [title, packages] of [
  ["Rust crates", rust],
  ["JavaScript packages", npm],
]) {
  lines.push(title, "-".repeat(title.length), "");
  for (const pkg of packages) {
    const where = refs(pkg);
    if (!where.length) missing.push(`${pkg.name} ${pkg.version}`);
    lines.push(`${pkg.name} ${pkg.version}`, `  ${pkg.licence}. ${pkg.source}`);
    lines.push(where.length ? `  ${where.join(", ")}` : "  No licence file in the package; the licence named above applies.");
    lines.push("");
  }
}
lines.push("Licence texts", "-------------", "");
for (const { number, text } of texts.values()) {
  lines.push(`[${number}]`, "", text, "", "-".repeat(72), "");
}

const out = join(root, "src-tauri", "licenses", "THIRD-PARTY-NOTICES.txt");
writeFileSync(out, lines.join("\n"));
console.log(`${rust.length} crates, ${npm.length} npm packages, ${texts.size} licence texts -> ${out}`);
if (missing.length) console.log(`no licence file in: ${missing.join(", ")}`);
